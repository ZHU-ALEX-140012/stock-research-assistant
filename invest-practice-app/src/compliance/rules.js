/* 词表完整性自检：硬拦截词没中性映射时，scanL1 会把违规词原文漏出去 */
export function neutralGap () {
  return [...new Set(L1_ENTRIES.map(e => e[0]))].filter(w => !NEUTRAL_MAP[w])
}

const L1_RE = new RegExp(L1_ENTRIES.map(x => x[0]).sort((a, b) => b.length - a.length)
  .map(w => w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g')

export function scanL1 (t) {
  const hits = []
  const text = String(t).replace(L1_RE, m => { hits.push(m); return NEUTRAL_MAP[m] || m })
  const cats = [...new Set(hits.map(h => (L1_ENTRIES.find(e => e[0] === h) || [])[1]).filter(Boolean))]
  return { text, hits, cats }
}

