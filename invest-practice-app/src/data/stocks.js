const SEEDS = { 600036: 32.8, '000651': 28.4, 601988: 3.9, 600519: 1620.0 }

function buildSeries (base, ph) {
  const arr = []
  let p = base * 0.93
  for (let i = 0; i < 52; i++) {
    const w = Math.sin(i * 0.55 + ph) * 0.013 + Math.sin(i * 0.17 + 1.3 + ph * 1.7) * 0.010 + Math.cos(i * 1.31 + ph * 0.6) * 0.004
    p = p * (1 + w)
    arr.push(p)
  }
  const k = base / arr[arr.length - 1]
  return arr.map(v => v * k)
}

function makeStock (cfg) {
  const ph = ((parseInt(cfg.code.slice(-2), 10) % 11) + 1) * 0.83
  const s = buildSeries(SEEDS[cfg.code], ph)
  const upper = Math.max(...s)
  const lower = Math.min(...s)
  const price = s[s.length - 1]
  const pos = (price - lower) / (upper - lower)
  return Object.assign({}, cfg, {
    series: s, price: price.toFixed(2), upper: upper.toFixed(2), lower: lower.toFixed(2), pos,
    vol: { avg30: (Math.round(38 + pos * 55) / 10), ratio: (0.86 + pos * 0.42).toFixed(2), turnover: (0.45 + pos * 1.6).toFixed(2) }
  })
}

